typedef struct {
  drmModeConnector *connector;
  drmModeModeInfo *mode;
  drmModeEncoder *encoder;
  uint32_t crtc_id;
  int crtc_idx;
} DisplayTarget;

typedef struct {
  int fd;
  uint32_t fb_id;
  uint32_t width;
  uint32_t height;
  uint32_t crtc_id;
  void *map;
  uint32_t handle;
  uint32_t pitch;
  uint64_t size;
} KMSFramebuffer;

static int find_connected_display(int fd, drmModeRes *res, DisplayTarget *target) {
  for (int i = 0; i < res->count_connectors; i++) {
    drmModeConnector *conn = drmModeGetConnector(fd, res->connectors[i]);
    if (!conn)
      continue;
    if (conn->connection == DRM_MODE_CONNECTED && conn->count_modes > 0) {
      target->connector = conn;
      target->mode = &conn->modes[0];
      printf("Found connector %d: %dx%d %s\n", conn->connector_id, target->mode->hdisplay,
             target->mode->vdisplay, target->mode->name);

      if (conn->count_encoders > 0) {
        drmModeEncoder *enc = drmModeGetEncoder(fd, conn->encoders[0]);
        if (enc && enc->crtc_id) {
          target->encoder = enc;
          target->crtc_id = enc->crtc_id;
          for (int j = 0; j < res->count_crtcs; j++) {
            if (res->crtcs[j] == target->crtc_id)
              target->crtc_idx = j;
          }
          return 0;
        }
        if (enc)
          drmModeFreeEncoder(enc);
      }

      for (int j = 0; j < res->count_encoders; j++) {
        drmModeEncoder *enc = drmModeGetEncoder(fd, res->encoders[j]);
        if (!enc)
          continue;
        for (int k = 0; k < res->count_crtcs; k++) {
          if (enc->possible_crtcs & (1 << k)) {
            target->encoder = enc;
            target->crtc_id = res->crtcs[k];
            target->crtc_idx = k;
            return 0;
          }
        }
        drmModeFreeEncoder(enc);
      }
      drmModeFreeConnector(conn);
      target->connector = NULL;
    } else {
      drmModeFreeConnector(conn);
    }
  }
  return -1;
}

static int create_fb(int fd, uint32_t width, uint32_t height, KMSFramebuffer *fb) {
  struct drm_mode_create_dumb creq = {0};
  creq.width = width;
  creq.height = height;
  creq.bpp = 32;
  if (drmIoctl(fd, DRM_IOCTL_MODE_CREATE_DUMB, &creq) < 0) {
    perror("DRM_IOCTL_MODE_CREATE_DUMB");
    return -1;
  }

  fb->handle = creq.handle;
  fb->pitch = creq.pitch;
  fb->size = creq.size;

  struct drm_mode_map_dumb mreq = {0};
  mreq.handle = creq.handle;
  if (drmIoctl(fd, DRM_IOCTL_MODE_MAP_DUMB, &mreq) < 0) {
    perror("DRM_IOCTL_MODE_MAP_DUMB");
    return -1;
  }

  fb->map = mmap(0, creq.size, PROT_READ | PROT_WRITE, MAP_SHARED, fd, mreq.offset);
  if (fb->map == MAP_FAILED) {
    perror("mmap");
    return -1;
  }

  uint32_t handles[4] = {creq.handle, 0, 0, 0};
  uint32_t pitches[4] = {creq.pitch, 0, 0, 0};
  uint32_t offsets[4] = {0, 0, 0, 0};
  uint32_t fb_id;
  if (drmModeAddFB2(fd, width, height, DRM_FORMAT_XRGB8888, handles, pitches, offsets, &fb_id, 0) < 0) {
    perror("drmModeAddFB2");
    munmap(fb->map, creq.size);
    return -1;
  }

  fb->fd = fd;
  fb->fb_id = fb_id;
  fb->width = width;
  fb->height = height;
  fb->crtc_id = 0;
  return 0;
}

static void fill_rect(KMSFramebuffer *fb, int x, int y, int w, int h, uint32_t color) {
  uint32_t *pixels = (uint32_t *)fb->map;
  for (int row = y; row < y + h && row < (int)fb->height; row++) {
    for (int col = x; col < x + w && col < (int)fb->width; col++) {
      pixels[row * (fb->pitch / 4) + col] = color;
    }
  }
}

