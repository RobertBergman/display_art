static void draw_char(KMSFramebuffer *fb, int x, int y, char c, uint32_t color, int scale) {
  if (c < 32 || c > 126)
    return;
  const uint8_t *glyph = font[c - 32];
  for (int row = 0; row < 7; row++) {
    for (int col = 0; col < 5; col++) {
      if (glyph[col] & (1 << row)) {
        for (int sy = 0; sy < scale; sy++) {
          for (int sx = 0; sx < scale; sx++) {
            int px = x + col * scale + sx;
            int py = y + row * scale + sy;
            if (px >= 0 && px < (int)fb->width && py >= 0 && py < (int)fb->height) {
              uint32_t *pixels = (uint32_t *)fb->map;
              pixels[py * (fb->pitch / 4) + px] = color;
            }
          }
        }
      }
    }
  }
}

static void draw_string(KMSFramebuffer *fb, int x, int y, const char *str, uint32_t color, int scale) {
  int cx = x;
  for (const char *c = str; *c; c++) {
    draw_char(fb, cx, y, *c, color, scale);
    cx += 6 * scale;
  }
}

static void draw_horizontal_line(KMSFramebuffer *fb, int x1, int x2, int y, uint32_t color) {
  uint32_t *pixels = (uint32_t *)fb->map;
  if (y < 0 || y >= (int)fb->height)
    return;
  int start = x1 < 0 ? 0 : x1;
  int end = x2 >= (int)fb->width ? (int)fb->width - 1 : x2;
  for (int x = start; x <= end; x++) {
    pixels[y * (fb->pitch / 4) + x] = color;
  }
}

int main(int argc, char **argv) {
  const char *card = argc > 1 ? argv[1] : "/dev/dri/card1";
  int fd = open(card, O_RDWR);
  if (fd < 0) {
    perror("open");
    return 1;
  }

  drmModeRes *res = drmModeGetResources(fd);
  if (!res) {
    perror("drmModeGetResources");
    close(fd);
    return 1;
  }

  DisplayTarget target = {0};
  if (find_connected_display(fd, res, &target) < 0) {
    fprintf(stderr, "No connected display found on %s\n", card);
    drmModeFreeResources(res);
    close(fd);
    return 1;
  }

  KMSFramebuffer fb = {0};
  if (create_fb(fd, target.mode->hdisplay, target.mode->vdisplay, &fb) < 0) {
    fprintf(stderr, "Failed to create framebuffer\n");
    drmModeFreeConnector(target.connector);
    drmModeFreeEncoder(target.encoder);
    drmModeFreeResources(res);
    close(fd);
    return 1;
  }

  memset(fb.map, 0, fb.size);

  uint32_t bg_color = 0xFF1a1a2e;
  uint32_t accent = 0xFFe94560;
  uint32_t text_color = 0xFFf0f0f0;

  fill_rect(&fb, 0, 0, fb.width, fb.height, bg_color);

  int char_w = 6 * 4;
  int text_px = (fb.width - 11 * char_w) / 2;
  int text_py = (fb.height - 7 * 4) / 2;
  draw_string(&fb, text_px, text_py, "Hello World", text_color, 4);

  draw_horizontal_line(&fb, text_px, text_px + 11 * char_w, text_py + 7 * 4 + 8, accent);
  draw_horizontal_line(&fb, text_px, text_px + 11 * char_w, text_py + 7 * 4 + 10, accent);

  printf("Setting mode %dx%d on CRTC %d, connector %d, encoder %d\n", target.mode->hdisplay,
         target.mode->vdisplay, target.crtc_id, target.connector->connector_id, target.encoder->encoder_id);

  int ret = drmModeSetCrtc(fd, target.crtc_id, fb.fb_id, 0, 0, &target.connector->connector_id, 1,
                           target.mode);
  if (ret < 0) {
    perror("drmModeSetCrtc");
    drmModeRmFB(fd, fb.fb_id);
    munmap(fb.map, fb.size);
    drmModeFreeConnector(target.connector);
    drmModeFreeEncoder(target.encoder);
    drmModeFreeResources(res);
    close(fd);
    return 1;
  }

  printf("Displaying... Press Enter to exit.\n");
  getchar();

  drmModeSetCrtc(fd, target.crtc_id, 0, 0, 0, NULL, 0, NULL);

  drmModeRmFB(fd, fb.fb_id);
  munmap(fb.map, fb.size);

  {
    struct drm_mode_destroy_dumb dreq = {0};
    dreq.handle = fb.handle;
    drmIoctl(fd, DRM_IOCTL_MODE_DESTROY_DUMB, &dreq);
  }

  drmModeFreeConnector(target.connector);
  drmModeFreeEncoder(target.encoder);
  drmModeFreeResources(res);
  close(fd);
  printf("Done.\n");
  return 0;
}
